#pragma once

namespace mode2::params
{
    // OnsetDetector
    // 온셋 사이 최소 간격 = 같은 줄을 빠르게 반복해서 칠 때 놓치는 하한. 0.08s는 16분음표
    // 기준 약 188bpm에서 이미 온셋을 흘리기 시작한다. 0.05s면 300bpm까지 여유가 있다.
    constexpr float onsetMinIntervalSeconds = 0.05f;
    constexpr float onsetAdaptiveThresholdMultiplier = 1.6f;
    constexpr float onsetEnergyFloor = 1.0e-4f;
    // 자기상관은 아주 작은 주기성 잡음에도 높은 confidence를 낼 수 있다. 실제 기타가
    // 들어오지 않는 레벨에서는 피치 결과를 무효화해 목표 음표가 잡음 위를 걷지 않게 한다.
    constexpr float guitarPitchRmsFloor = 0.002f;

    // PitchStabilizer
    // 목표 확정까지 걸리는 시간 = attackSettle + (collectRequiredStableBlocks × 블록 길이).
    // 여기가 길면 코드를 바꿔도 보정 목표가 늦게 따라온다.
    // 피킹 직후 분석창 안에 남은 이전 음과 어택 잡음이 빠질 시간을 준다. 샘플레이트에
    // 따라 창의 "샘플 수"를 바꾸더라도 실제 창 길이는 약 43ms로 유지하므로, 절반을 조금
    // 넘긴 25ms 뒤부터 새 목표를 수집한다.
    constexpr float attackSettleSeconds = 0.025f;
    // 새 음으로 바뀐 직후에는 피치 검출 윈도우(2048샘플 ≒ 46ms)에 아직 이전 음이 섞여 있어
    // 추정치가 흔들린다. 허용 오차가 좁으면 그때마다 카운트가 1로 되돌아가 확정이 계속
    // 밀리므로, 창이 비워지는 동안의 흔들림을 흡수할 만큼은 넉넉히 둔다.
    constexpr float collectConvergenceToleranceSemitones = 0.5f;
    // 기타 목표는 아래에서 반음 양자화+히스테리시스를 이미 거친다. 같은 음표를 두 번 더
    // 기다리면 24kHz/512 환경에서 43ms가 추가되므로 한 번의 깨끗한 창으로 확정한다.
    constexpr int collectRequiredStableBlocks = 1;
    // STABLE에서 이 오차 안의 피치 변화는 재조준 없이 즉시 목표에 반영한다. 0.6반음은 스케일
    // 인접음(1~2반음)조차 "이탈"로 보기 때문에, 빠른 스케일에서 매 음마다 3블록 이탈 확인 +
    // COLLECT 2블록 = 약 53ms 동안 이전 음을 물고 있다가 넘어가 소리가 끊긴다. 3반음으로
    // 넓히면 스케일 스텝과 벤딩·비브라토를 다음 블록에 바로 따라간다. 옥타브 오류(12반음)는
    // 여전히 이 범위를 넘어 재조준 경로로 빠지므로 걸러진다.
    constexpr float stableToleranceSemitones = 3.0f;

    // STABLE에서 검출 피치가 허용 오차를 벗어난 상태가 이만큼 연속되면 목표를 다시 잡는다.
    // 온셋 없이 음이 바뀌는 경우(레가토, 부드러운 코드 전환, 울리는 중 운지 변경)를 잡기 위한
    // 경로다. 1블록만 보고 재조준하면 순간적인 검출 튐에도 목표가 흔들리므로 여러 블록을 본다.
    constexpr int stableReacquireBlocks = 2;
    // 확정된 음표의 중앙에서 이 거리 안이면 같은 음표로 유지한다. 0.5보다 크게 둬서
    // 프렛 잡음·벤딩이 반음 경계를 잠깐 넘는 것만으로 목표가 왕복하지 않게 한다.
    constexpr float guitarNoteHysteresisSemitones = 0.65f;
    constexpr float coastHoldSeconds = 0.35f;
    constexpr float coastFadeSeconds = 0.25f;

    // VocalDelayBuffer 제어 lookahead — 제어 경로(피치 추정)와 오디오 경로의 정렬량.
    //
    // 이전 값은 21.3ms였다. 근거는 "보컬 피치는 43ms 창으로 분석하니 추정값은 창 중앙,
    // 즉 21ms 전의 음을 나타낸다. 오디오도 21ms 늦추면 시점이 맞는다"였다.
    //
    // 출력 음정 정확도 지표(tools/PitchAccuracyMetrics.*)로 실제로 쓸어보니 그 추론이 틀렸다.
    // 오차는 정렬량에 대해 단조 증가했고 0에서 최소였다. 즉 이 검출기의 추정값은 창 중앙이
    // 아니라 창의 최신 끝에 가깝게 대응한다. 오디오를 늦출수록 추정이 설명하는 음성보다
    // 오래된 음성을 처리하게 되어 오차가 커진다.
    //
    // 합성 신호 2종(비브라토 있는 목소리 / 거기에 잡음 추가), Rubber Band, --octave=0:
    //     정렬     21.3ms          10ms           5ms            0ms
    //   중앙값   17.3 / 18.2   13.0 / 14.5   10.8 / 13.2    8.4 / 11.4 cents
    //   ±20c내   61 / 55%      87 / 67%      94 / 71%       95 / 74%
    // ±50 cents 이내 비율은 전 구간 97/95%로 평평했다. 즉 음 전환 품질은 손해 보지 않고
    // 미세 정확도만 좋아진다. 덤으로 전체 지연이 21ms 줄어든다.
    //
    // 이 값은 Mode2Offline의 --lookahead로 다시 스윕할 수 있다. 실제 녹음으로 재검증할 때
    // 값이 달라지면 그 결과를 따르면 된다.
    constexpr float vocalControlLookaheadSeconds = 0.0f;

    // CorrectionCalculator
    // 1.0 = 목표 음에 완전히 붙인다. 1보다 작으면 오차의 (1-strength)만큼이 남는데, 그 잔차는
    // "목표에서 얼마나 벗어나 불렀는지"에 비례하므로 같은 코드를 쳐도 높게/낮게 부를 때마다
    // 결과 음이 달라진다. 자연스러운 흔들림을 남기고 싶으면 0.9 정도로 낮추면 된다.
    constexpr float pitchFollowStrength = 1.0f;

    // 목표 음을 옥타브 단위로 옮긴다. 0 = 기타 음 그대로, -1 = 한 옥타브 아래.
    // 절대 목표 로직에서 0은 실제 기타 옥타브 그대로, -1은 정확히 한 옥타브 아래다.
    // 실제 녹음은 기타가 보컬보다 약 한 옥타브 높아 0에서 중앙값 +14.51반음이 필요하지만,
    // -1에서는 +2.51반음이면 된다. 같은 기타 음의 출력 옥타브는 어느 쪽이든 고정되므로
    // 음색 손상이 작은 -1을 기본으로 쓴다.
    constexpr int targetOctaveShift = -1;
    constexpr int targetOctaveShiftMin = -3;
    constexpr int targetOctaveShiftMax = 2;

    // PitchShifterEngine
    // 시프트량 변경 속도(반음/초) = 글라이드(포르타멘토) 속도. 목표가 바뀔 때 그 음까지
    // 미끄러지는 빠르기다. 높으면 즉시 점프(계단식), 낮으면 레가토처럼 이어진다.
    //   350 → 2반음 6ms   (사실상 즉시)
    //   250 → 2반음 8ms   (클릭만 막고 글라이드는 거의 안 들림)
    //   120 → 2반음 17ms  (글라이드가 뚜렷하게 들림)
    //    30 → 2반음 67ms  (과한 슬라이드)
    //
    // 이 값은 목표가 바뀔 때만 작용하는 게 아니다. 보정량은 (목표 − 내 음정)이라서 내 목소리가
    // 흔들리면 그걸 상쇄하려고 보정량도 계속 움직인다. 글라이드를 낮추면 그 상쇄가 늦어져
    // 출력 음정이 내 목소리를 따라 흔들리고, 이게 부자연스러운 미끄러짐으로 들린다.
    // 그래서 기본값은 클릭만 막을 정도로 빠르게 두고, 레가토가 필요하면 화면에서 낮춘다.
    constexpr float defaultGlideSemitonesPerSecond = 250.0f;
    constexpr float glideRateMin = 10.0f;
    constexpr float glideRateMax = 600.0f;

    // SoundTouch WSOLA 파라미터. auto 모드는 tempo=1.0에서 sequence를 73ms로 잡아 음 변화가
    // 뭉개지므로 직접 지정한다. 다만 짧게 할수록 좋은 게 아니다 — WSOLA는 시퀀스 안에서 이어붙일
    // 지점을 찾으므로 시퀀스에 출력 파형 주기가 최소 2개는 들어와야 한다.
    //
    // 오프라인 측정(입력 A3 220Hz, 하향 시프트별 출력 깨끗함):
    //            출력음    seq20    seq40    seq60
    //   -15반음   92.5Hz   95.1%   99.9%   100.0%
    //   -19반음   73.4Hz   13.1%   99.3%    99.9%   ← seq20에서 붕괴
    //   -22반음   61.7Hz   28.6%   98.0%    99.8%
    // seq20은 작은 시프트에서는 아무 손해가 없어서 문제를 놓치기 쉽다. 큰 하향 시프트에서만
    // 무너지므로(주기가 길어져 시퀀스에 2개가 안 들어옴) 40ms로 둔다. 위로 올리는 시프트는
    // 주기가 짧아지므로 어느 설정에서도 100%다.
    //
    // 대가: 시퀀스+시크+오버랩 지연이 약 36ms → 63ms로 늘어난다.
    constexpr int pitchShiftSequenceMs = 40;
    constexpr int pitchShiftSeekWindowMs = 15;
    constexpr int pitchShiftOverlapMs = 8;
    // 상관 탐색을 근사로 처리하는 quick seek는 CPU는 줄지만 이어붙일 위치의 품질을
    // 희생한다. 현재 우선순위는 CPU보다 "다른 음/소음이 섞인 듯한" WSOLA 아티팩트를
    // 줄이는 것이므로 정확 탐색을 기본으로 쓴다.
    constexpr bool pitchShiftUseQuickSeek = false;

    // SoundTouch의 큰 하향 피치 시프트는 포먼트와 자음 대역까지 함께 내려 목소리가 어둡고
    // 묻혀 들린다. 원본을 섞으면 원래 음정이 다시 들리므로 시프트된 단일 경로의 고역만
    // 완만하게 보강한다. Rubber Band는 포먼트를 직접 보존하므로 이 보정을 적용하지 않는다.
    // amount=0.65는 SoundTouch 최대 하향 시프트에서 고역을 약 +4.3dB 올리는 값이다.
    constexpr float timbrePresenceCutoffHz = 1600.0f;
    constexpr float timbrePresenceAmount = 0.65f;
    constexpr float timbrePresenceFullShiftSemitones = 12.0f;

    // 피치 검출 탐색 하한(Hz). 하한이 낮으면 배주기 피크까지 후보에 들어와 한 옥타브 아래로
    // 오검출한다. 대상 음역에 맞춰 최대한 높게 잡아야 한다.
    //
    // 기타는 6번줄 개방현 E2(82Hz)를 잡아야 하므로 70이 필요하다.
    // 목소리는 실측 결과 MIDI 47~60(123~262Hz) 범위였는데, 하한이 70이라 배주기 오검출이
    // MIDI 37~42(69~92Hz)에 나타났다. 접기를 끈 뒤로는 이 12반음 오차가 그대로 출력에 나가
    // 음정이 옥타브 단위로 튄다("띠용" 소리). 하한을 100으로 올리면 그 오검출들은 탐색 범위
    // 밖이 되어 애초에 선택될 수 없다. 대신 G2(98Hz) 아래로 부르는 저음은 검출되지 않는다.
    constexpr float guitarPitchMinFrequencyHz = 70.0f;
    constexpr float vocalPitchMinFrequencyHz = 100.0f;

    // 탐색 상한. 이게 넓으면 배음 피크가 후보에 들어와 한 옥타브 위로 오검출한다.
    // MPM은 "최대 피크의 90% 이상 중 가장 짧은 주기"를 고르므로, 2배 주파수 피크가 그 문턱을
    // 넘으면 그쪽을 택한다.
    //
    // 실측: 목소리 실제 음역은 MIDI 48~60(130~262Hz)인데 상한 1200Hz(MIDI 86) 탓에 검출이
    // MIDI 73~85(587~1109Hz)로 튀었고, 그 결과 보정량이 블록 사이에 12~21반음씩 도약했다.
    // 450Hz(≈A4, MIDI 69.7)로 조이면 그 오검출들이 탐색 범위 밖이 된다.
    // 대신 A4보다 높게 노래하면 검출되지 않는다.
    constexpr float vocalPitchMaxFrequencyHz = 450.0f;
    // 기타는 하이 프렛까지 쓰므로 넓게 둔다(1번줄 12프렛 E5 = 659Hz).
    constexpr float guitarPitchMaxFrequencyHz = 1200.0f;

    // 자기상관 분석 창(샘플). 길면 관측 주기 수가 늘어 추정이 안정되고, 짧으면 반응이 빠르다.
    //
    // 오프라인 측정 결과: 고정 시프트에서 SoundTouch 출력은 비배음 에너지 0.0%로 완벽히 깨끗한데,
    // 시프트가 ±0.5반음만 흔들려도 13~32%, ±3반음이면 63~95%가 비배음이 된다(= 음이 아니라 소음).
    // 즉 이 파이프라인이 요구하는 목소리 음정 정밀도는 ±0.5반음 수준이다. 그런데 실측 voc는
    // ±6반음을 오갔다. 목소리 쪽 창을 두 배로 늘려 관측 주기 수를 두 배로 만든다.
    //
    // 아래 값은 48kHz 기준 샘플 수다. 실제 prepare 시 현재 샘플레이트에 비례해 바꿔서
    // 24kHz 장치에서도 창 길이가 두 배(85/171ms)로 늘어나지 않게 한다.
    // 기타와 목소리 모두 약 42.7ms의 실제 시간을 유지한다. 목소리 창을 85ms로 두면
    // 사용자가 음높이를 바꾼 뒤 보정량이 그만큼 늦게 반대로 움직여, 출력이 잠시 목소리를
    // 따라간다. 출력 피치를 기타에 고정하려면 목소리 변화도 기타만큼 빨리 읽어야 한다.
    constexpr int guitarPitchWindowSize = 2048;
    constexpr int vocalPitchWindowSize = 2048;
    constexpr double pitchWindowReferenceSampleRate = 48000.0;

    inline int scalePitchWindowForSampleRate(int referenceSamples, double sampleRate)
    {
        const int scaled = static_cast<int>(referenceSamples * sampleRate
                                            / pitchWindowReferenceSampleRate + 0.5);
        return scaled < 256 ? 256 : scaled;
    }

    // 목소리 피치 추정치에 적용하는 미디언 필터 길이(블록). 기타 쪽은 PitchStabilizer가
    // 흔들림을 걸러주는데 목소리 쪽에는 아무 스무딩이 없어서, 검출 지터가 그대로 보정량에
    // 들어가고 출력 음정(= 실제음정 + 보정량)이 같은 폭으로 떨린다.
    //
    // 실측: 110Hz 부근을 부를 때 voc가 43.8~49.2(5.4반음)를 매 블록 왕복했고 신뢰도는 0.9+였다.
    // 신뢰도로는 걸러낼 수 없는 지터라서 값 자체를 안정화해야 한다. 저음일수록 창(2048샘플)
    // 안에 들어오는 주기 수가 적어(110Hz면 3.7개) 추정이 불안정해지는 게 근본 이유다.
    //
    // 옥타브 언랩을 별도로 적용하므로 5탭까지 기다릴 필요가 없다. 3탭은 단발성 이상치를
    // 제거하면서 실질 지연을 한 블록으로 줄여 목소리 변화 상쇄를 빠르게 한다.
    constexpr int vocalPitchMedianTaps = 3;

    // 신뢰도 게이트 — 이 아래면 드라이로 감쇠(M2-4).
    // 실측에서 정상 검출은 conf 0.72~0.98, 옥타브 오검출은 대부분 0.38~0.56에 몰렸다.
    // 탐색 하한 상향으로 걸러지지 않은 오검출을 잡는 2차 방어선으로 0.65에 둔다.
    constexpr float vocalConfidenceGateThreshold = 0.65f;

    // 신뢰도를 wet/dry 비율로 환산하면(비례 블렌드) 자음·숨·음 전환처럼 신뢰도가 순간적으로
    // 떨어지는 구간마다 보정 안 된 원본 목소리가 그대로 새어 나온다. 원본은 내가 부른 음이라
    // 기타 음에 안 맞고, 결과적으로 "내 목소리 음이 남는" 소리가 된다.
    //
    // 그래서 기타 쪽 상태기계와 같은 HOLD/FADE 방식을 쓴다: 한번 신뢰도를 확보하면 순간적인
    // 하락에는 직전 보정을 유지하면서 완전 wet을 지키고, 아래 시간만큼 계속 잃었을 때만
    // 드라이로 되돌린다. 원본 혼합은 추종 실패 시의 대비책이지 평소 음색 요소가 아니다.
    // 신뢰도 게이트를 0.65로 올려 거부되는 블록이 늘었으므로, 그만큼 유지 시간도 늘려
    // wet이 껌뻑이지 않게 한다(실측에서 0.15초로는 유지가 끝나 드라이로 떨어지는 구간이 잦았다).
    constexpr float vocalConfidenceHoldSeconds = 0.3f;
    constexpr float vocalConfidenceFadeSeconds = 0.12f;

    // 그런데 HOLD/FADE로도 부족했다. 기타 유입이 있으면 신뢰도가 게이트 아래에 오래 머물러,
    // 유입 -2dB 조건의 오프라인 측정에서 목소리가 있는 블록의 9.3%가 wet=0(원본 100%)까지
    // 떨어졌다. 그 구간의 스펙트럼에는 보정 안 된 원본 음정이 그대로 찍힌다.
    //
    // 애초에 "드라이로 되돌린다"는 대비책 자체가 증상을 만든다. 원본은 내가 부른 음이므로
    // 기타 음에 맞지 않고, 듣는 사람에게는 그냥 틀린 음이 끼어드는 것으로 들린다. 반면 신뢰도가
    // 떨어지는 실제 원인은 대부분 무성음(자음·숨)인데, 무성음에는 음정이 없어서 직전 보정량으로
    // 시프트한 채 내보내도 어색하지 않다. 목소리가 정말로 멈추면 노이즈 게이트가 닫아준다.
    //
    // 그래서 기본값은 "드라이로 되돌리지 않음"이다. 사양서 M2-4의 원래 동작이 필요하면 켠다.
    constexpr bool vocalConfidenceFallbackToDry = false;

    // --- 기타 유입 상쇄(GuitarBleedCanceller) ---------------------------------
    // 목소리 마이크에 새어 들어온 기타를, 별도 채널로 이미 들어와 있는 기타 신호를 참조로 써서
    // 지운다. 합성 측정에서 유입이 있으면 출력 명료도가 0.98 → 0.67까지 떨어지고, 상쇄하면
    // 0.94로 돌아온다. 즉 유입이 있는 환경에서는 매우 효과적이다.
    //
    // 그런데 기본값은 끔이다. 실제 녹음(기타는 Scarlett 라인 입력, 목소리는 에어팟 마이크)을
    // 재보니 유입이 아예 없었다: 기타가 RMS 0.051로 크게 울리는 순간에도 목소리 채널은
    // 0.00084(-35.8dB, 잡음 바닥)였고, 두 채널의 코히런스는 0.002였다. 그 녹음에 상쇄를 켜면
    // 걷어내는 양이 -0.19dB(= 뺄 게 없음)인데 명료도만 0.96 → 0.94로 내려갔다.
    //
    // 켜야 하는 경우는 목소리 마이크가 기타를 실제로 줍는 환경이다(내장 마이크로 둘 다 받거나,
    // 기타 앰프 앞에서 노래하는 경우). 화면 토글의 제거량 표시가 판단 기준이다 — 노래를 쉬고
    // 기타만 칠 때 그 값이 몇 dB 이상 나오면 유입이 있다는 뜻이니 켜 두면 되고, 0 근처면 끈다.
    constexpr bool defaultBleedCancelEnabled = false;

    // FIR 길이(탭). 기타 → 마이크 음향 경로의 직접음과 초기 반사를 덮을 만큼은 필요하다.
    // 44.1kHz에서 256탭 = 5.8ms ≒ 소리가 2m 가는 시간.
    //
    // 짧게 잡는 것이 "안전"하지 않다. 오프라인 측정(지연 1.2ms + 반사 4.0/7.5ms 경로):
    //         유입 없음        유입 -2dB
    //    48탭  33.3% / 0.49    42.0% / 0.47   ← 직접음 지연(1.2ms=53샘플)도 못 덮어 엉뚱한 걸 뺀다
    //    96탭  75.0% / 0.73    71.0% / 0.67
    //   192탭  86.3% / 0.88    86.4% / 0.87
    //   256탭  91.2% / 0.95    89.7% / 0.94   ← 채택
    //   384탭  91.0% / 0.95    89.8% / 0.95
    //   512탭  91.3% / 0.95    90.4% / 0.95
    // 256을 넘으면 사실상 평평하고 연산량만 비례해 는다. 반대로 경로 지연을 못 덮을 만큼
    // 짧으면 상쇄기가 도움이 아니라 피해가 된다.
    constexpr int bleedCancelFilterTaps = 256;

    // NLMS 스텝. 목소리는 참조와 상관이 없어 NLMS 입장에서는 잡음이므로, 크게 두면 노래하는
    // 동안 계수가 목소리를 따라 출렁여 오히려 목소리를 깎는다. 작게 두고 여러 블록에 걸쳐
    // 평균이 수렴하게 한다(0.08이면 실측상 1~2초 안에 대부분 수렴).
    constexpr float bleedCancelStepSize = 0.08f;
    constexpr float bleedCancelRegularization = 1.0e-6f;

    // 참조(기타) RMS가 이 아래면 학습을 멈춘다. 기타가 쉬는 동안 계수가 목소리 쪽으로 끌려가면
    // 정작 기타가 들어올 때 엉뚱한 것을 빼게 된다.
    constexpr float bleedCancelReferenceRmsFloor = 0.002f;

    // 가변 스텝의 하한. 실효 스텝을 (추정된 유입 / 목소리 채널 전체)에 비례해 줄인다.
    //
    // 왜 필요한가: 목소리는 참조와 무관하므로 NLMS에게는 잡음이고, 노래하는 동안 계수가 그
    // 잡음을 따라 출렁인다(미스어드저스트먼트). 측정하면 유입이 "전혀 없는" 조건에서도 상쇄를
    // 켜는 것만으로 배음 비율이 88.0% → 83.1%로 떨어졌다. 뺄 게 없는데 뭔가를 빼고 있다는 뜻.
    //
    // 비율로 스텝을 조절하면 세 상황이 저절로 갈린다:
    //   - 기타만 울리는 순간(구절 사이, 숨): 추정 ≒ 전체 → 스텝 최대, 빠르게 수렴
    //   - 노래 중: 전체 ≫ 추정 → 스텝이 줄어 계수가 사실상 얼어붙는다
    //   - 유입이 아예 없음: 추정이 계속 0 근처 → 스텝이 하한에 머물러 계수가 거의 안 움직인다
    // 하한이 0이면 계수가 0인 초기 상태에서 영원히 학습을 시작하지 못하므로 0보다 커야 한다.
    //
    // 실효: 384탭 기준으로 고정 스텝(=1.0) 88.5%/0.91 → 가변 스텝 91.0%/0.95.
    constexpr float bleedCancelAdaptFloor = 0.15f;

    // 계수 누설. 오래 학습하며 관측되지 않은 방향으로 계수가 표류하는 것을 막는다.
    constexpr float bleedCancelLeakage = 1.0e-7f;

    // 제거량 표시용 레벨 EMA 계수(블록 단위).
    constexpr float bleedCancelLevelEmaCoeff = 0.05f;

    // 노이즈 게이트: 말하지 않는 구간의 실내 잡음·기타 유입·하울링 성장을 끊는다.
    // 판정은 부스트 적용 후 목소리 RMS로 한다(화면의 "목소리 입력 레벨"과 같은 기준).
    // 하울링을 더 세게 억제하기 위해 기본 임계를 높이고, 말이 끝나면 빠르게 닫히도록
    // hold/release를 짧게 잡는다(말꼬리가 짧게 잘릴 수 있으면 슬라이더로 낮추면 된다).
    // 주의: 이 임계는 "부스트를 적용한 뒤"의 RMS와 비교된다. 따라서 defaultVocalInputGain을
    // 바꾸면 이 값도 같이 바꿔야 한다. 둘을 따로 건드리면 게이트가 잡음에 열리거나(임계가
    // 상대적으로 낮음) 목소리에도 안 열린다(상대적으로 높음).
    //
    // 내장 마이크 실측(원시 RMS): 잡음 바닥 0.003~0.013(정상 구간은 0.006~0.009),
    // 목소리 보통 0.035, 작게 부르면 0.015, 목소리+기타 0.073.
    //
    // 0.08은 원시 0.02에서 열리는 값이라 작게 부르는 목소리(0.015)를 놓쳤다. 원시 0.012에서
    // 열리도록 낮춘다(0.012 × 부스트 4 = 0.048). 정상 잡음(부스트 후 0.024~0.036)보다 위,
    // 작은 목소리(0.06)보다 아래다. 닫는 임계는 히스테리시스 0.6배로 0.029가 되어 정상 잡음
    // 위에 남는다. 순간적으로 튀는 잡음(원시 0.013 → 0.052)은 여전히 게이트를 열 수 있다.
    // 부스트를 4.0 → 2.0으로 낮췄으므로 임계도 절반으로 내린다. 이 임계는 부스트 후 RMS와
    // 비교되므로, 한쪽만 바꾸면 원시 트리거 지점이 0.012 → 0.024로 올라가 작은 목소리를 놓친다.
    // AirPods 마이크 실측: 목소리 RMS 0.063, 잡음 바닥 0.001~0.004(내장 마이크보다 훨씬 조용).
    // 부스트 2배 적용 시 목소리 0.126, 잡음 0.002~0.008 → 0.024는 그 사이에 넉넉히 들어간다.
    constexpr float vocalNoiseGateThreshold = 0.024f;

    // 목소리 입력 부스트 기본값. 내장 마이크는 입에서 멀어 레벨이 매우 낮아 1.0으로는 게이트
    // 임계에도, 피치 검출 신뢰도에도 못 미친다. 반대로 너무 올리면(8배 이상) 목소리+기타가
    // 섞인 구간에서 리미터에 걸린다. 화면 슬라이더로 조절할 수 있다.
    // 제대로 된 XLR 마이크를 Scarlett INPUT 1에 물리면 이 값을 1~2로 낮춰야 한다.
    // AirPods 마이크는 내장 마이크보다 3배 뜨겁다(목소리 RMS 0.063 vs 0.021). 4.0으로 두면
    // 목소리+기타 구간에서 리미터에 2.63% 걸려 하드 클리핑이 생긴다(오프라인 측정).
    constexpr float defaultVocalInputGain = 2.0f;

    // 최종 출력 볼륨 기본값. 출력을 키우는 건 입력 부스트가 아니라 이 값으로 해야 한다.
    // 입력 부스트는 목소리와 잡음을 같이 키워 신호 대 잡음비가 그대로지만, 이 값은 노이즈
    // 게이트와 노치를 통과한 뒤에 걸린다. 실측 목소리(부스트 후 RMS 0.14)에 1.5를 곱하면
    // 0.21이 되고 피크는 약 0.7로 리미터(0.95) 아래에 있다. 기타가 크게 섞인 구간에서는
    // 리미터가 걸릴 수 있다. 화면 슬라이더 범위는 0~2다.
    constexpr float defaultOutputVolume = 1.0f;

    // 하울링 억제 기본 상태. 오프라인 측정 결과 이 억제가 출력 음질을 가장 크게 해쳤다:
    // 켜면 깨끗함 중앙값 96.0% → 92.0%, 최악 25% 구간은 87.7% → 75.0%로 떨어진다.
    // 노치 억제기가 배음을 직접 깎고, 트립 게이트가 정상 노래를 되먹임으로 오판해 블록을
    // 통째로 묵음시키기 때문이다. 헤드폰·이어폰으로 모니터링하면 되먹임 경로가 물리적으로
    // 없으므로 기본은 끈다. 스피커로 모니터링할 때만 화면에서 켜면 된다.
    constexpr bool defaultHowlGuardEnabled = false;
    // 닫는 임계는 여는 임계보다 낮게 둬서 임계 근처 떨림을 막는다.
    constexpr float noiseGateHysteresisRatio = 0.6f;
    // 말 시작을 놓치지 않게 어택은 빠르게, 되먹임이 자랄 틈을 주지 않게 릴리스는 짧게.
    constexpr float noiseGateAttackSeconds = 0.005f;
    constexpr float noiseGateReleaseSeconds = 0.06f;
    // 짧은 무음(자음 사이 등)에 닫히지 않도록 유지 시간을 둔다.
    constexpr float noiseGateHoldSeconds = 0.05f;

    // 레벨 미터의 100% 기준 RMS. 게이트 임계 슬라이더도 같은 눈금을 쓴다.
    constexpr float levelMeterReferenceRms = 0.3f;

    // 하울링 자동 억제(7절 리스크 대응): 출력 레벨이 지속적으로 높게 유지되면 되먹임으로
    // 보고 게인을 빠르게 줄이고, 잠잠해지면 천천히 회복한다.
    constexpr float feedbackDuckOutputThreshold = 0.25f;
    constexpr float feedbackDuckAttackPerBlock = 0.82f;
    constexpr float feedbackDuckRecoveryPerBlock = 0.004f;
    constexpr float feedbackDuckMinimumGain = 0.08f;
    constexpr float outputLevelEmaCoeff = 0.2f;

    // 출력 리미터: 어떤 경우에도 폭주하지 않도록 마지막에 걸어두는 상한.
    constexpr float outputLimitPeak = 0.95f;

    // 출력 하울링 트립 게이트: feedbackDuck*은 천천히 눌러 내리는 방식이라 되먹임이 이미
    // 자란 뒤에는 반응이 느리다. 이건 출력이 기준을 넘는 순간 그 블록을 즉시 완전 묵음
    // 시키는 훨씬 강한 마지막 수단이다. 판정은 직전 블록의 출력 RMS로 한다(한 블록 지연,
    // feedbackDuck과 같은 구조).
    constexpr float outputTripThreshold = 0.35f;
    // 한번 트립되면 이 시간 동안은 레벨이 내려가도 무조건 묵음을 유지한다(바로 풀리면
    // 되먹임이 곧장 다시 차오르며 껌뻑거리게 된다).
    constexpr float outputTripHoldSeconds = 0.4f;
    // 유지 시간이 끝난 뒤 게인을 1.0까지 되돌리는 속도(블록당 증가량). 급하게 열면 다시
    // 트립되기 쉬우므로 서서히 되돌린다.
    constexpr float outputTripRecoveryPerBlock = 0.01f;
}
